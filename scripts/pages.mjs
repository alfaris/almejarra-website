// Generates one HTML entry per language and page (/, /en/, /team/, /en/team/) plus sitemap.xml,
// so every URL ships its own <title>, description, canonical, hreflang and share tags.
// Edit titles and descriptions in src/content/meta.json, then run `npm run pages`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const meta = JSON.parse(readFileSync(join(root, 'src/content/meta.json'), 'utf8'))
const site = meta.siteUrl

const pages = [
  { lang: 'ar', page: 'home', path: '' },
  { lang: 'en', page: 'home', path: 'en/' },
  { lang: 'ar', page: 'team', path: 'team/' },
  { lang: 'en', page: 'team', path: 'en/team/' },
]

const pathFor = (lang, page) => pages.find((p) => p.lang === lang && p.page === page).path
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')

const jsonLd = {
  '@context': 'https://schema.org',
  '@type': 'CoworkingSpace',
  name: 'AlMejarra المجرة',
  alternateName: 'المجرة مساحة عمل مشتركة',
  url: site,
  logo: `${site}images/logo.png`,
  image: `${site}${meta.ogImage}`,
  email: 'connect@almejarra.com',
  telephone: ['+201005048220'],
  foundingDate: '2015-01-12',
  address: {
    '@type': 'PostalAddress',
    streetAddress: '7 Omar Ibn El-Khattab St., University Villas',
    addressLocality: 'Zagazig',
    addressRegion: 'Sharqia',
    addressCountry: 'EG',
  },
  geo: { '@type': 'GeoCoordinates', latitude: 30.587802, longitude: 31.487646 },
  sameAs: [
    'https://facebook.com/almejarra',
    'https://instagram.com/almejarra',
    'https://x.com/almejarra',
    'https://www.linkedin.com/company/almejarra-المچرة',
    'https://youtube.com/almejarra',
  ],
}

function html({ lang, page, path }) {
  const m = meta[lang][page]
  const depth = path.split('/').filter(Boolean).length
  const appRoot = depth ? '../'.repeat(depth) : './'
  const other = lang === 'ar' ? 'en' : 'ar'
  const alternates = ['ar', 'en']
    .map((l) => `    <link rel="alternate" hreflang="${l}" href="${site}${pathFor(l, page)}" />`)
    .concat(`    <link rel="alternate" hreflang="x-default" href="${site}${pathFor('ar', page)}" />`)
    .join('\n')
  const ld = page === 'home' ? `\n    <script type="application/ld+json">${JSON.stringify(jsonLd)}</script>` : ''
  return `<!doctype html>
<!-- Generated by scripts/pages.mjs from src/content/meta.json. Do not edit by hand. -->
<html lang="${lang}" dir="${lang === 'ar' ? 'rtl' : 'ltr'}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />
    <meta name="theme-color" content="#120a1c" />
    <meta name="app-root" content="${appRoot}" />
    <title>${esc(m.title)}</title>
    <meta name="description" content="${esc(m.description)}" />
    <link rel="icon" type="image/jpeg" href="/favicon.jpg" />
    <link rel="apple-touch-icon" href="/favicon.jpg" />
    <link rel="canonical" href="${site}${path}" />
${alternates}

    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="AlMejarra المجرة" />
    <meta property="og:title" content="${esc(m.title)}" />
    <meta property="og:description" content="${esc(m.description)}" />
    <meta property="og:url" content="${site}${path}" />
    <meta property="og:image" content="${site}${meta.ogImage}" />
    <meta property="og:locale" content="${lang === 'ar' ? 'ar_EG' : 'en_US'}" />
    <meta property="og:locale:alternate" content="${other === 'ar' ? 'ar_EG' : 'en_US'}" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:site" content="@almejarra" />${ld}
  </head>
  <body>
    <div id="root"></div>
    <noscript>${esc(m.title)} · connect@almejarra.com · 01005048220</noscript>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
`
}

for (const p of pages) {
  const file = join(root, p.path, 'index.html')
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, html(p))
}

const urls = pages
  .map(
    (p) => `  <url>
    <loc>${site}${p.path}</loc>
${['ar', 'en'].map((l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${site}${pathFor(l, p.page)}" />`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${site}${pathFor('ar', p.page)}" />
  </url>`,
  )
  .join('\n')
writeFileSync(
  join(root, 'public/sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls}
</urlset>
`,
)
writeFileSync(join(root, 'public/robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site}sitemap.xml\n`)
console.log(`Generated ${pages.length} pages, sitemap.xml and robots.txt`)
